-- Mahjong per-game (per-MATCH) trophy accumulator.
--
-- Mahjong is the hard case for per-game trophies: a match is MANY hands, and
-- `processMahjongNextHand` (src/lib/mahjong.ts) WIPES per-hand state every hand — it
-- overwrites `mahjong_player_state.melds`, `discarded`, `seat` and re-deals the hand, and
-- nulls the session's `winner_player_id` / `score_summary`. So anything a trophy needs to
-- remember about a hand (a Kong you called, a hand you won, three wins in a row) is GONE the
-- instant the next hand is dealt. A finish-time facts builder (unlike Chess's PGN replay or
-- Yahtzee's scorecard) would find nothing left to read.
--
-- This column is the trace that survives that wipe. `game_counters` is a per-MATCH scratch
-- blob the engine bumps AT HAND RESOLUTION and during play (see src/lib/mahjong.ts and
-- src/lib/mahjong-hand-resolution.ts), folded into lifetime trophy counters at match finish by
-- src/lib/trophies/game-facts/mahjong.ts. It accumulates across every hand of the one match.
--
-- ############################################################################################
-- ## DELIBERATE PRESERVATION ACROSS processMahjongNextHand — DO NOT ADD IT TO THE HAND RESET ##
-- ############################################################################################
-- `processMahjongNextHand` resets the per-hand columns (melds/discarded/seat/…) but MUST leave
-- `game_counters` intact — it is per-MATCH, not per-hand. The engine achieves this by never
-- clobbering the column: the next-hand update merges the existing blob forward (only bumping
-- the seat bitmask / win-streak bookkeeping) rather than resetting it. If a future edit adds
-- `game_counters` to that reset, every hand would erase the match's trophy progress and every
-- Mahjong per-game trophy would silently become unearnable. The per-MATCH reset is instead the
-- row's own lifecycle: `initializeMahjongGame` and `clearMahjongSessionData` DELETE these rows
-- on start / play-again, so the blob is naturally reborn empty for each new match.
--
-- Shape (all optional, absent == 0). COUNTS (summed into lifetime totals at finish):
--   mahjong_discards, mahjong_chows_called, mahjong_pungs_called, mahjong_kongs_called,
--   mahjong_concealed_kongs, mahjong_added_kongs, mahjong_hands_as_east,
--   mahjong_exhaustive_draws_seen, mahjong_hands_won, mahjong_seven_pairs_wins,
--   mahjong_thirteen_orphans_wins, mahjong_self_draw_wins, mahjong_concealed_wins,
--   mahjong_no_call_wins, mahjong_won_fate_round, mahjong_won_hong_kong, mahjong_won_riichi,
--   mahjong_won_mcr, mahjong_triple_meld, mahjong_four_melds, mahjong_double_kong,
--   mahjong_grand_slam, mahjong_quick_hand, mahjong_high_fan, mahjong_heavenly_hand.
-- INTERNAL per-match state (NEVER summed — the facts builder reads these to derive 0/1 flags):
--   mahjong_seat_mask   (bit i set == played a hand in seat i; all four == bitmask 15),
--   mahjong_win_streak, mahjong_win_streak_max (longest run of consecutive hand wins).

alter table mahjong_player_state
  add column if not exists game_counters jsonb not null default '{}'::jsonb;

-- NO grant is added, deliberately. `mahjong_player_state` is a SERVER-ONLY table: migration
-- 20260803180100_sec_service_role_only_hidden_state.sql enabled RLS with NO policies and
-- removed it from the realtime publication, because the row holds each player's hidden tiles.
-- Anon/authenticated have no read path to any column of this table (the client reads redacted
-- state through API routes), so there is no table- or column-level SELECT grant to mirror. The
-- server writes and reads `game_counters` with the service role, which bypasses RLS entirely.

